Q('What is a dbt model?', 'Models', minutes=7, cards=[
    definition(
        defbox('A <strong>model</strong> is a <code>.sql</code> file in the <code>models/</code> folder containing exactly <strong>one SELECT '
               'statement</strong>. dbt builds it into a database object (view, table…) named after the file. Models reference each other with '
               '<code>ref()</code>, configure themselves with <code>config()</code>, and can use Jinja and macros.',
               'Since dbt 1.3, some adapters (Snowflake, BigQuery, Databricks) also support <strong>Python models</strong> returning a DataFrame.'),
        tags('Model', 'SELECT', 'ref', 'config', 'Python Model'),
    ),
    analogy('A model is like a <strong>recipe card</strong>: it only lists what goes into the dish (SELECT … FROM …), not how to set up the kitchen. '
            'dbt is the kitchen staff that reads the card and produces the dish in the right container (view or table).'),
    model_anim(),
    real_world(
        scenario('A team writing models',
                 p('A new analyst adds <code>models/marts/fct_attendance_monthly.sql</code> with a GROUP BY query. She never writes CREATE TABLE or '
                   'manages drops; dbt creates the table in her dev schema, and after review the production job creates it in the prod schema.')),
    ),
    example(
        dfile('models/staging/stg_marks.sql', STG_MARKS),
        dfile('models/marts/subject_results.sql', """
{{ config(materialized='table') }}

select
    subject,
    count(*)                                   as attempts,
    round(avg(marks), 1)                       as avg_marks,
    sum(case when marks >= 60 then 1 else 0 end) as passed
from {{ ref('stg_marks') }}
group by subject
order by subject
"""),
        dbtrun('!dbt seed', 'dbt run', 'dbt --quiet show --select subject_results'),
        title='Example'),
    steps(
        ('Create a .sql file in models/', 'Its name becomes the object name, so use clear names (fct_, dim_, stg_).'),
        ('Write one SELECT', 'No trailing semicolon, no DDL.'),
        ('Reference inputs with ref() / source()', 'Never hard-code schema.table.'),
        ('Optionally configure', '<code>{{ config(materialized=\'table\') }}</code> at the top.'),
        ('Build and preview', '<code>dbt run --select model</code>, <code>dbt show --select model</code>.'),
        title='Steps to Create a Model'),
    crossq(
        ('Can a model contain several SELECT statements or DML?', 'No. One final SELECT (CTEs are fine). Inserts/updates are generated by dbt from the materialization; extra SQL belongs in hooks or macros.'),
        ('Why no semicolon at the end?', 'dbt wraps the SELECT inside its own DDL; a trailing semicolon would break the generated statement on many warehouses.'),
    ),
]),

