Q('How do you structure models into staging, intermediate and mart layers?', 'Staging / Intermediate / Marts', minutes=9, cards=[
    definition(
        table(['Layer', 'Prefix', 'Purpose', 'Typical materialization'], [
            ['Staging', '<code>stg_</code>', '1:1 with a source table: rename, cast, clean, standardise; no joins, no aggregation', 'view'],
            ['Intermediate', '<code>int_</code>', 'Reusable transformation steps: joins, pivots, business logic', 'ephemeral or view'],
            ['Marts', '<code>fct_</code>, <code>dim_</code>', 'Business-facing facts and dimensions for BI/ML', 'table / incremental'],
        ]),
        tags('Staging', 'Intermediate', 'Marts', 'Fact', 'Dimension', 'Modular Modeling'),
    ),
    analogy('Like processing exam papers: <strong>staging</strong> is receiving and sorting papers into a standard format; <strong>intermediate</strong> is '
            'evaluation and totalling; <strong>marts</strong> are the final result sheets published to students and management.'),
    layers_anim(),
    real_world(
        scenario('Why layering paid off',
                 p('When the exam system renamed <code>roll_no</code> to <code>student_roll</code>, only <code>stg_marks</code> changed. Twenty downstream '
                   'models kept using <code>student_id</code> from staging and needed no edits.')),
    ),
    example(
        *[dfile(k, v, show=False) for k, v in STAGING.items()],
        dfile('models/intermediate/int_student_scores.sql', """
-- one row per student: total and average across subjects
select
    student_id,
    count(*)            as subjects,
    sum(marks)          as total_marks,
    round(avg(marks), 1) as avg_marks
from {{ ref('stg_marks') }}
group by student_id
"""),
        dfile('models/marts/dim_students.sql', """
select s.student_id, s.student_name, s.centre, c.course_name,
       sc.subjects, sc.avg_marks
from {{ ref('stg_students') }} s
left join {{ ref('stg_courses') }} c using (course_code)
left join {{ ref('int_student_scores') }} sc using (student_id)
order by s.student_id
"""),
        dbtrun('!dbt seed', 'dbt run', 'dbt --quiet show --select dim_students --limit 10'),
        title='Example'),
    steps(
        ('Create one staging model per source table', 'Rename to consistent names, cast types.'),
        ('Extract reusable logic into intermediate models', 'Pivots, joins used by several marts.'),
        ('Build marts per business area', '<code>marts/academics/</code>, <code>marts/placements/</code>.'),
        ('Set materializations per folder', 'In dbt_project.yml.'),
        ('Expose only marts to BI users', 'Grant access to the marts schema.'),
        title='Steps to Layer a Project'),
    crossq(
        ('Should staging models join tables?', 'No. Joins belong in intermediate or mart models; staging stays a clean 1:1 interface to each source.'),
        ('Where do you put a model used by many marts?', 'In intermediate (or as a shared dimension in marts) and ref it from each consumer, instead of duplicating SQL.'),
    ),
]),
