Q('What are sources? How do you check source freshness?', 'Sources & Freshness', minutes=8, cards=[
    definition(
        defbox('<strong>Sources</strong> declare the raw tables loaded by other tools, in YAML: a source name, the schema, and the tables. Models read '
               'them with <code>{{ source(\'source_name\', \'table_name\') }}</code>. Sources appear in lineage, can have tests and descriptions, and '
               'can define <strong>freshness</strong> rules: with a <code>loaded_at_field</code>, <code>dbt source freshness</code> warns or errors if the '
               'newest row is older than a threshold.'),
        tags('source()', 'Sources', 'Freshness', 'loaded_at_field', 'Raw Layer'),
    ),
    analogy('Sources are the <strong>suppliers list</strong> of the kitchen: which vendor delivers what, and when it was last delivered. If the milk '
            'delivery is two days late (freshness), the head chef is alerted before cooking with old milk.'),
    source_anim(),
    real_world(
        scenario('Catching a broken loader',
                 p('The exam-results loader silently stopped on a Sunday. The Monday 6 a.m. Airflow DAG ran <code>dbt source freshness</code> first: '
                   '<code>raw_exam.marks</code> was 30 hours old, above the 24-hour error threshold, so the DAG stopped and alerted the team '
                   'before stale results were published.')),
    ),
    example(
        dfile('models/staging/_sources.yml', """
sources:
  - name: exam_db
    schema: dev_raw              # where the loader writes (here: our seeds)
    tables:
      - name: raw_marks
        description: Marks exported nightly from the exam system
        loaded_at_field: cast(exam_date as timestamp)
        freshness:
          warn_after: {count: 1, period: day}
          error_after: {count: 30, period: day}
"""),
        dfile('models/staging/stg_exam_marks.sql', """
select roll_no as student_id, subject, marks
from {{ source('exam_db', 'raw_marks') }}
"""),
        dbtrun('!dbt seed', 'dbt run', 'dbt source freshness', allow_fail=True),
        note('The newest <code>exam_date</code> in the sample data is 2026-10-11, more than a day before this page was built, so freshness reports WARN '
             '(above warn_after, below error_after).', 'Read the output'),
        title='Example'),
    steps(
        ('List raw tables in a sources .yml', 'Name, schema (and database), tables.'),
        ('Replace hard-coded names', 'Use <code>source()</code> in staging models only.'),
        ('Add freshness rules', '<code>loaded_at_field</code> + warn/error thresholds.'),
        ('Run freshness first in the pipeline', '<code>dbt source freshness</code> before <code>dbt build</code>.'),
        ('Test raw keys', 'not_null/unique on source columns catch loader problems early.'),
        title='Steps to Declare Sources'),
    crossq(
        ('ref() vs source()?', 'ref() points to objects dbt builds (models, seeds, snapshots); source() points to tables something else loads.'),
        ('Why should only staging models use source()?', 'It keeps one clean entry point per raw table; all other models build on staging, so raw-schema changes affect one place.'),
    ),
]),

