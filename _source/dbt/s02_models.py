Q('What is ref()? How does dbt build the DAG and lineage?', 'ref() & the DAG', minutes=8, cards=[
    definition(
        defbox('<code>{{ ref(\'model_name\') }}</code> refers to another model (or seed/snapshot). At compile time it becomes the fully qualified '
               'relation for the current target (<code>"cdac"."dev"."stg_marks"</code>), and it records a <strong>dependency</strong>. All refs '
               'together form a <strong>Directed Acyclic Graph (DAG)</strong>: dbt uses it to order builds, run independent models in parallel, '
               'support graph selection (<code>+model</code>) and draw lineage in docs.'),
        tags('ref', 'DAG', 'Lineage', 'Dependencies', 'Directed Acyclic Graph'),
    ),
    analogy('<code>ref()</code> is like writing "<strong>see chapter 3</strong>" instead of copying its page numbers: the book can be re-printed in '
            'any format (dev or prod) and the cross-references stay correct, and an editor can draw a map of which chapters depend on which.'),
    dag_anim(),
    real_world(
        scenario('Impact analysis before a change',
                 p('Before renaming a column in <code>stg_marks</code>, the engineer runs <code>dbt ls --select stg_marks+</code> to list every '
                   'downstream model and checks the lineage graph for dashboards (exposures) that would be affected.')),
    ),
    example(
        dfile('models/staging/stg_students.sql', STG_STUDENTS, show=False),
        dfile('models/staging/stg_marks.sql', STG_MARKS, show=False),
        dfile('models/staging/stg_courses.sql', STG_COURSES, show=False),
        dfile('models/marts/dim_students.sql', """
select s.student_id, s.student_name, s.centre, c.course_code, c.course_name
from {{ ref('stg_students') }} s
join {{ ref('stg_courses') }}  c using (course_code)
"""),
        dfile('models/marts/fct_marks.sql', """
select m.student_id, d.course_code, m.subject, m.marks, m.exam_date
from {{ ref('stg_marks') }} m
join {{ ref('dim_students') }} d using (student_id)
"""),
        dbtrun('!dbt seed', 'dbt run', 'dbt --quiet ls --select +fct_marks', 'dbt --quiet ls --select stg_students+'),
        title='Example: Order Comes From ref()'),
    steps(
        ('Use ref() for every model/seed dependency', 'And source() for raw tables.'),
        ('Avoid circular references', 'dbt refuses to run a cycle (A refs B, B refs A).'),
        ('Explore the graph', '<code>dbt ls --select +model+</code> or the lineage view in dbt docs.'),
        title='Steps'),
    crossq(
        ('What happens if you hard-code "dev.stg_marks" instead of using ref()?', 'dbt does not know the dependency: it may build models in the wrong order, the prod run would read the dev schema, and lineage would be incomplete.'),
        ('Can ref() point to another project?', 'Yes, with dbt Mesh: <code>ref(\'other_project\', \'model\')</code> for public models (dbt Cloud Enterprise).'),
    ),
]),

