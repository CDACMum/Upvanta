Q('What are seeds? When should you use them?', 'Seeds', minutes=6, cards=[
    definition(
        defbox('<strong>Seeds</strong> are CSV files in <code>seeds/</code> that <code>dbt seed</code> loads into tables. They are version-controlled and '
               'referenced with <code>ref()</code>. Use them for <strong>small, static reference data</strong>: mappings, code lists, thresholds. You can '
               'set column types with <code>+column_types</code>.'),
        tags('Seeds', 'dbt seed', 'CSV', 'Reference Data', 'column_types'),
    ),
    analogy('Seeds are the <strong>laminated reference charts</strong> on the staff-room wall (grade bands, centre codes): small, rarely changed, and '
            'everyone can see who changed them (Git history).'),
    seed_anim(),
    real_world(
        scenario('Grade bands as a seed',
                 p('The academic council changes grade boundaries once a year. Keeping them in <code>seeds/grade_bands.csv</code> means the change is a '
                   'reviewed pull request, and every model joining to the seed picks it up on the next run.')),
    ),
    example(
        dfile('seeds/grade_bands.csv', """
grade,min_marks,max_marks
A,85,100
B,70,84
C,60,69
F,0,59
"""),
        dfile('models/staging/stg_marks.sql', STG_MARKS, show=False),
        dfile('models/marts/marks_with_grade.sql', """
select m.student_id, m.subject, m.marks, g.grade
from {{ ref('stg_marks') }} m
join {{ ref('grade_bands') }} g
  on m.marks between g.min_marks and g.max_marks
order by m.student_id, m.subject
"""),
        dbtrun('dbt seed --select grade_bands', '!dbt seed', 'dbt run', 'dbt --quiet show --select marks_with_grade --limit 10'),
        title='Example'),
    steps(
        ('Add the CSV to seeds/', 'Header row with column names.'),
        ('Optionally set types', '<code>seeds: cdac_dw: grade_bands: +column_types: {min_marks: integer}</code>.'),
        ('Load', '<code>dbt seed</code> (<code>--full-refresh</code> if columns changed).'),
        ('Use with ref()', 'Join like any model.'),
        title='Steps to Add a Seed'),
    crossq(
        ('Why not load a 2 GB file as a seed?', 'Seeds are inserted row by row through dbt, are slow for large files, and bloat the Git repository. Load big data with an EL tool or the warehouse\'s bulk COPY and declare it as a source.'),
    ),
]),

